class LanguageNotifier extends Notifier<String> {
  @override
  String build() {
    _loadLanguage();
    return 'en';
  }

  Future<void> _loadLanguage() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final savedLang = prefs.getString('app_language');
      if (savedLang != null) {
        state = savedLang;
      }
    } catch (_) {}
  }

  Future<void> setLanguage(String langCode) async {
    state = langCode;
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString('app_language', langCode);
    } catch (_) {}
  }
}

final languageProvider = NotifierProvider<LanguageNotifier, String>(() {
  return LanguageNotifier();
});

class TranslationHelper {
  final String currentLanguage;
  TranslationHelper(this.currentLanguage);

  String translate(String key) {
    return AppLocalization.translate(key, currentLanguage);
  }

  String call(String key) => translate(key);
}

final translationProvider = Provider<TranslationHelper>((ref) {
  final lang = ref.watch(languageProvider);
  return TranslationHelper(lang);
});
